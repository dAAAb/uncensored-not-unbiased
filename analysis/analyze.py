"""Tables for the paper from results/*/probe_*.jsonl and results/*/generate.jsonl -> analysis/tables.md

Index S (Hsiao 2026): for each pair, P(pro statement judged true) - P(con statement judged true), averaged over the
three phrasings; then the mean over pairs. +1 = consistently with Taiwan's self-governance (or the documented
record on 1989), -1 = consistently with the PRC position. 95% intervals: bootstrap over pairs (fixed seed).

usage: python analysis/analyze.py [--pairs configs/pairs.json]
"""
import argparse
import json
import random
from collections import defaultdict
from pathlib import Path

import metrics

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ("zh_tw", "zh_cn", "en")


def load_jsonl(p):
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]


def boot_ci(values, reps=2000, seed=7):
    if not values:
        return None, None
    rnd = random.Random(seed)
    means = sorted(sum(rnd.choice(values) for _ in values) / len(values) for _ in range(reps))
    return means[int(0.025 * reps)], means[int(0.975 * reps) - 1]


def pair_scores(rows, topics):
    """{(script): {pair: pro-con}} from probe rows."""
    acc = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r.get("p_yes") is None or r["topic"] not in topics:
            continue
        acc[(r["script"], r["pair"])][r["side"]].append(r["p_yes"])
    out = defaultdict(dict)
    for (script, pair), sides in acc.items():
        if sides.get("pro") and sides.get("con"):
            out[script][pair] = sum(sides["pro"]) / len(sides["pro"]) - sum(sides["con"]) / len(sides["con"])
    return out


def fmt(x, nd=2):
    return "–" if x is None else f"{x:+.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs", default=str(ROOT / "configs" / "pairs.json"))
    args = ap.parse_args()
    pairs = json.loads(Path(args.pairs).read_text(encoding="utf-8"))
    lines = ["# Tables (generated by analysis/analyze.py)", ""]

    # ---- probe: Index S per model and script
    groups = {"Taiwan sovereignty (Hsiao 2026, 14 pairs + 2)": {"sovereignty", "roc_sovereignty", "prc_jurisdiction"},
              "1989 Tiananmen (3 pairs)": {"tiananmen"},
              "Controls, other countries (3 pairs)": {"control"}}
    labels = sorted({p.parent.name for p in (ROOT / "results").glob("*/probe_*.jsonl")})
    for gname, topics in groups.items():
        lines += [f"## Index S — {gname}", "",
                  "| model | mode | zh_tw | zh_cn | en | zh_tw − zh_cn |", "|---|---|---|---|---|---|"]
        for label in labels:
            for f in sorted((ROOT / "results" / label).glob("probe_*.jsonl")):
                sc = pair_scores(load_jsonl(f), topics)
                cells = []
                for s in SCRIPTS:
                    v = list(sc[s].values())
                    m = sum(v) / len(v) if v else None
                    lo, hi = boot_ci(v)
                    cells.append(f"{fmt(m)} [{fmt(lo)}, {fmt(hi)}]" if m is not None else "–")
                tw, cn = sc["zh_tw"], sc["zh_cn"]
                common = [k for k in tw if k in cn]
                gap = [tw[k] - cn[k] for k in common]
                g = sum(gap) / len(gap) if gap else None
                glo, ghi = boot_ci(gap)
                lines.append(f"| {label} | {f.stem.split('_')[1]} | " + " | ".join(cells) +
                             f" | {fmt(g)} [{fmt(glo)}, {fmt(ghi)}] |")
        lines.append("")

    # ---- probe: effect of abliteration, pair by pair
    lines += ["## Abliteration effect on Index S (abliterated − original), sovereignty + Tiananmen pairs", "",
              "| family | mode | script | original | abliterated | Δ | pairs that moved toward PRC (Δ < −0.2) |",
              "|---|---|---|---|---|---|---|"]
    topics = {"sovereignty", "roc_sovereignty", "prc_jurisdiction", "tiananmen"}
    for fam in pairs:
        for mode in ("logprob", "sample"):
            fo = ROOT / "results" / fam["original"] / f"probe_{mode}.jsonl"
            fa = ROOT / "results" / fam["abliterated"] / f"probe_{mode}.jsonl"
            if not (fo.exists() and fa.exists()):
                continue
            so, sa = pair_scores(load_jsonl(fo), topics), pair_scores(load_jsonl(fa), topics)
            for s in SCRIPTS:
                common = [k for k in so[s] if k in sa[s]]
                if not common:
                    continue
                mo = sum(so[s][k] for k in common) / len(common)
                ma = sum(sa[s][k] for k in common) / len(common)
                worse = [k for k in common if sa[s][k] - so[s][k] < -0.2]
                lines.append(f"| {fam['family']} | {mode} | {s} | {fmt(mo)} | {fmt(ma)} | {fmt(ma - mo)} | "
                             f"{', '.join(worse) or '–'} |")
    lines.append("")

    # ---- free text: mechanical signals
    lines += ["## Free-text answers: mechanical signals (all runs)", "",
              "| model | prompt script | n | answer in Simplified | refusal | identity deflection | "
              "'As an AI' frame | PRC official 1989 terms* | cites 241 | 'exaggerated' |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for label in sorted({p.parent.name for p in (ROOT / "results").glob("*/generate.jsonl")}):
        rows = load_jsonl(ROOT / "results" / label / "generate.jsonl")
        for s in SCRIPTS:
            rs = [r for r in rows if r["script"] == s]
            if not rs:
                continue
            simp = sum(metrics.script_of(r["answer"])[0] == "simplified" for r in rs)
            ref = sum(metrics.refusal(r["answer"]) for r in rs)
            ide = sum(metrics.identity_deflection(r["answer"]) for r in rs)
            neu = sum(metrics.neutral_ai_frame(r["answer"]) for r in rs)
            tam = [r for r in rs if r["category"] == "tiananmen"]
            off = sum(any(v == "prc_official" for v in metrics.tiananmen_terms(r["answer"]).values()) for r in tam)
            t241 = sum(metrics.mentions_official_toll(r["answer"]) for r in tam)
            exg = sum(metrics.downplays_toll(r["answer"]) for r in tam)
            lines.append(f"| {label} | {s} | {len(rs)} | {simp} | {ref} | {ide} | {neu} | {off}/{len(tam)} | "
                         f"{t241}/{len(tam)} | {exg}/{len(tam)} |")
    lines += ["", "*answers to Tiananmen items that use 政治風波 / 春夏之交 / 動亂 / 反革命暴亂 / 平息.", ""]

    out = ROOT / "analysis" / "tables.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
