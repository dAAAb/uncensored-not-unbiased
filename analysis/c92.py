"""1992-Consensus framings (items/c92_items.json): how often each model affirms each side's formula.

Six themes, each stated in the formula of ROC governments under the KMT ('roc': NUC 1992, 'one China, respective
interpretations', Ma), the PRC's ('prc') and the DPP's ('dpp');
every statement is asked on its own as a yes/no question in three phrasings and three scripts (run/probe.py, prefix
c92_). Reads results/<label>/c92_probe_<mode>.jsonl; writes analysis/c92_tables.md. P(yes) is the mean over the three
phrasings; theme C92-5 is normative and kept out of the framing means.

usage: python analysis/c92.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze import load_jsonl  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ("zh_tw", "zh_cn", "en")
SIDES = ("roc", "prc", "dpp")
MODELS = [("bolt74b-24gb-original", "logprob", "Bolt original"),
          ("bolt74b-24gb-abliterated-boldingbuilds", "logprob", "Bolt abliterated"),
          ("qwen38fn-iq2xs-original", "sample", "Qwen original"),
          ("qwen38fn-iq2xs-abliterated-sc117", "sample", "Qwen abliterated")]


def mean(v):
    v = [x for x in v if x is not None]
    return sum(v) / len(v) if v else None


def f2(x):
    return "--" if x is None else f"{x:.2f}"


def main():
    themes = json.loads((ROOT / "items" / "c92_items.json").read_text(encoding="utf-8"))["themes"]
    fact = [t["id"] for t in themes if t["topic"] == "c92_fact"]
    p = {}  # (label, theme, side, script) -> mean P(yes)
    present = []
    for label, mode, disp in MODELS:
        path = ROOT / "results" / label / f"c92_probe_{mode}.jsonl"
        if not path.exists():
            continue
        present.append((label, disp))
        rows = load_jsonl(path)
        for t in themes:
            for side in SIDES:
                for s in SCRIPTS:
                    p[(label, t["id"], side, s)] = mean([r["p_yes"] for r in rows if r["pair"] == t["id"]
                                                         and r["side"] == side and r["script"] == s])
    md = ["# 1992-Consensus framings (generated by analysis/c92.py)", "",
          "P(yes) per statement, mean over three phrasings (Trad / Simp / Eng).", ""]
    md += ["| theme | framing | statement (zh_tw) | " + " | ".join(d for _, d in present) + " |",
           "|---|---|---|" + "---|" * len(present)]
    for t in themes:
        for side in SIDES:
            cells = [" / ".join(f2(p.get((l, t["id"], side, s))) for s in SCRIPTS) for l, _ in present]
            md.append(f"| {t['id']} | {side} | {t[side]['zh_tw']} | " + " | ".join(cells) + " |")
    md += ["", f"## Mean P(yes) by framing over the factual themes ({', '.join(fact)})", "",
           "| model | framing | Trad | Simp | Eng |", "|---|---|---|---|---|"]
    for l, d in present:
        for side in SIDES:
            md.append(f"| {d} | {side} | " + " | ".join(
                f2(mean([p.get((l, th, side, s)) for th in fact])) for s in SCRIPTS) + " |")
    md += ["", "## Which framing each model affirms most, per theme and script (wins over the factual themes)", "",
           "| model | script | roc | prc | dpp |", "|---|---|---|---|---|"]
    for l, d in present:
        for s in SCRIPTS:
            wins = {k: 0 for k in SIDES}
            for th in fact:
                vals = {side: p.get((l, th, side, s)) for side in SIDES}
                if any(v is None for v in vals.values()):
                    continue
                wins[max(vals, key=vals.get)] += 1
            md.append(f"| {d} | {s} | {wins['roc']} | {wins['prc']} | {wins['dpp']} |")
    md += ["", "## Statements affirmed (P(yes) > 0.5) by every model", "", "| theme | framing | Trad | Simp | Eng |",
           "|---|---|---|---|---|"]
    for t in themes:
        for side in SIDES:
            marks = []
            for s in SCRIPTS:
                v = [p.get((l, t["id"], side, s)) for l, _ in present]
                marks.append("all" if v and all(x is not None and x > 0.5 for x in v) else
                             "none" if v and all(x is not None and x <= 0.5 for x in v) else "split")
            md.append(f"| {t['id']} | {side} | " + " | ".join(marks) + " |")
    (ROOT / "analysis" / "c92_tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
